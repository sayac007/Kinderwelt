#!/usr/bin/env python3
"""Materialize a private family or fictional public cast without modifying saves.

The generated resource paths are ignored. Only public source art is versioned.
Legacy save IDs are intentionally stable in both variants.
"""
import argparse,hashlib,json,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
IDS=['wanja','mischa','du','mama','george','katze']
LOOKS=['classic','hero','alien','astronaut','scientist']
MANAGED=['core/quest/cast.gd','core/quest/cast.gd.uid','assets/quest/characters','assets/quest/cast.json','assets/quest/looks.json']

def selected(variant,root=ROOT):
    if variant=='auto':return 'family' if (root/'.private/characters/looks.json').is_file() else 'public'
    if variant not in ['family','public']:raise ValueError('Unknown cast variant')
    return variant

def prepare(output,variant='family',root=ROOT):
    variant=selected(variant,root);output=Path(output)
    if variant=='family' and not (root/'.private/characters/looks.json').is_file():
        raise ValueError('Private character pack is absent. Restore .private/characters or explicitly choose --variant public.')
    destination=output/'assets/quest/characters'
    if destination.exists():shutil.rmtree(destination)
    destination.mkdir(parents=True)
    sprites={};atlases={};looks={'schema':2,'variant':variant,'heroes':{}}
    if variant=='family':
        pack=root/'.private/characters';source=json.loads((pack/'looks.json').read_text())
        names=json.loads((pack/'names.json').read_text())
        for index,id in enumerate(IDS,1):
            normal=f'actor-{index}.png';dressed=f'outfits-{index}.png'
            shutil.copy2(pack/(id+'.png'),destination/normal);shutil.copy2(pack/('looks-'+id+'.png'),destination/dressed)
            sprites[id]='assets/quest/characters/'+normal;atlases[id]='assets/quest/characters/'+dressed
            data=source['heroes'][id].copy();data['file']='characters/'+dressed;looks['heroes'][id]=data
    else:
        source=root/'art/public/characters';catalog=json.loads((source/'catalog.json').read_text())
        image=source/catalog['source'];assert hashlib.sha256(image.read_bytes()).hexdigest()==catalog['sha256']
        shutil.copy2(image,destination/'neutral-cast.png');names=catalog['names']
        compiled=json.loads((source/'frames.json').read_text())
        assert compiled['source_sha256']==catalog['sha256'],'Public frame metadata is stale; run compile_public.py'
        for row,id in enumerate(IDS):
            data=compiled['heroes'][id];looks['heroes'][id]=data
            frames=data['frames']
            x,y,w,h=frames['classic'];name=f'actor-{row+1}.tres'
            (destination/name).write_text('[gd_resource type="AtlasTexture" load_steps=2 format=3]\n\n[ext_resource type="Texture2D" path="res://assets/quest/characters/neutral-cast.png" id="1"]\n\n[resource]\natlas = ExtResource("1")\nregion = Rect2(%s, %s, %s, %s)\nfilter_clip = true\n'%(x,y,w,h))
            sprites[id]='assets/quest/characters/'+name;atlases[id]='assets/quest/characters/neutral-cast.png'
    # The squirrel is original fictional art, shared in both variants.
    squirrel=json.loads((root/'art/shared/squirrel-looks.json').read_text())
    looks['heroes']['squirrel']=squirrel;names['squirrel']='Eichhörnchen'
    sprites['squirrel']='assets/quest/squirrel.png';atlases['squirrel']='assets/quest/looks-squirrel.png'
    manifest={'schema':1,'variant':variant,'names':names,'sprites':sprites,'atlases':atlases,'resource_sha256':{}}
    for path in sorted(set(sprites.values())|set(atlases.values())):
        manifest['resource_sha256'][path]=hashlib.sha256((output/path).read_bytes()).hexdigest()
    gd='extends RefCounted\n# Generated by scripts/variants.py; legacy save IDs are stable.\nconst FAMILY := '+('true' if variant=='family' else 'false')+'\nconst NAMES := '+json.dumps(names,ensure_ascii=False)+'\n'
    for name,values in [('SPRITES',sprites),('ATLASES',atlases)]:
        gd+='const '+name+' = {'+','.join(json.dumps(k)+':preload("res://'+v+'")' for k,v in values.items())+'}\n'
    (output/'core/quest').mkdir(parents=True,exist_ok=True)
    (output/'core/quest/cast.gd').write_text(gd)
    (output/'assets/quest/looks.json').write_text(json.dumps(looks,ensure_ascii=False,separators=(',',':'))+'\n')
    (output/'assets/quest/cast.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    return manifest

def snapshot(output,variant='family',root=ROOT):
    output=Path(output);output.mkdir(parents=True,exist_ok=False)
    def ignore(directory,names):
        relative=Path(directory).relative_to(root)
        return [n for n in names if str(relative/n) in MANAGED or n=='__pycache__']
    for name in ['core','games','assets','project.godot','export_presets.cfg']:
        src=root/name;dest=output/name
        if src.is_dir():shutil.copytree(src,dest,ignore=ignore)
        else:shutil.copy2(src,dest)
    return prepare(output,variant,root)

def export_public(output,root=ROOT):
    result=snapshot(output,'public',root)
    for name in ['scripts','tests','art','docs','.github']:
        def ignore(directory,names):
            return [n for n in names if n in ['internal','__pycache__'] or n.endswith(('.zip','.mp3'))]
        shutil.copytree(root/name,Path(output)/name,ignore=ignore)
    for name in ['README.md','.gitignore','.gitattributes','LICENSE']:
        if (root/name).exists():shutil.copy2(root/name,Path(output)/name)
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('command',choices=['prepare','snapshot','public-source']);p.add_argument('--variant',choices=['auto','family','public'],default='family');p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    result=export_public(a.output) if a.command=='public-source' else (prepare if a.command=='prepare' else snapshot)(a.output,a.variant)
    print('Prepared cast variant:',result['variant'])
if __name__=='__main__':main()
